# -*- coding: utf-8 -*-
"""Escritura de salidas con el formato exacto de AERSURFACE v26135 (mod_SfcChars.f:
Write_SfcChars; mod_GetData.f: Write_DbgGrid). Solo cambian las dos líneas de fecha/hora."""
import datetime as dt

import numpy as np

from .formato import fmt_f, fmt_i, nint

VERSION = "26135"
_I3 = {v: f"{v:3d}" for v in range(-999, 1000)}      # formato I3 precalculado (rejillas)
LBL = ["Late autumn after frost and harvest, or winter with no snow",
       "Winter with continuous snow on the ground",
       "Transitional spring (partial green coverage, short annuals)",
       "Midsummer with lush vegetation",
       "Autumn with unharvested cropland"]


def _cabecera(texto, ahora=None):
    t = ahora or dt.datetime.now()
    l1 = f"** {texto}".ljust(66) + t.strftime("%m/%d/%y") + " **"
    l2 = "**".ljust(66) + t.strftime("%H:%M:%S") + " **"
    return [l1, l2, ""]


def _ids_no_aeropuerto(c):
    if c.vary_ap:
        ids = [str(i + 1) for i in range(c.num_sectores) if not c.sec_ap[i][1]]
        if not ids:
            return "None"
        if len(ids) == c.num_sectores:
            return "All"
        return " ".join(ids)
    if not c.airport and not c.sect_ring:
        return "All"
    if c.sect_ring:
        return "Sector Rings"
    return "None"


def escribir_sfc(path, c, r, ahora=None):
    L = _cabecera(f"Generated by AERSURFACE, Version {VERSION}", ahora)
    L.append(f"** Title 1: {c.titulo1}")
    if c.titulo2.strip():
        L.append(f"** Title 2: {c.titulo2}")
    L.append("** Primary Site (Zo):")
    if c.coord_tipo == "UTM":
        L.append(f"**   Center UTM Easting  (meters): {fmt_f(c.utm_e, 10, 1)}")
        L.append(f"**   Center UTM Northing (meters): {fmt_f(c.utm_n, 10, 1)}")
        L.append(f"**   UTM Zone: {fmt_i(c.utm_zona, 3)}  Datum: {c.datum}")
    else:
        L.append(f"**   Center Latitude  (decimal degrees): {fmt_f(c.lat, 12, 6)}")
        L.append(f"**   Center Longitude (decimal degrees): {fmt_f(c.lon, 12, 6)}")
        L.append(f"**   Datum: {c.datum}")
    L.append(f"** NLCD Version:  {fmt_i(c.nlcd_year, 4)}")
    L.append(f"** NLCD DataFile: {getattr(c, '_lc_nombre', c.lc_file)}")
    if r.use_imp and len(c.imp_file) > 3:
        L.append(f"** MPRV Version:  {fmt_i(c.imp_year, 4)}")
        L.append(f"** MPRV DataFile: {getattr(c, '_imp_nombre', c.imp_file)}")
    if r.use_can and len(c.can_file) > 3:
        L.append(f"** CNPY Version:  {fmt_i(c.can_year, 4)}")
        L.append(f"** CNPY DataFile: {getattr(c, '_can_nombre', c.can_file)}")
    L.append(f"** High Z0 (Non-Airport) Sector IDs: {_ids_no_aeropuerto(c)}")
    L.append(f"** Zo Method: {c.metodo_zo}")
    if c.zo_eff_flg:
        L.append(f"** Anemometer Height (m): {fmt_f(c.anem_height, 6, 2)}")
        L.append(f"** IBL Factor: {fmt_f(c.ibl_factor, 5, 1)}")
    elif c.zo_rad_flg:
        L.append(f"** Zo Radius (m): {fmt_f(c.zo_rad, 8, 1)}")
    L.append(f"** Continuous snow cover: {c.nieve_chr}")
    L.append(f"** Surface moisture: {c.humedad_txt};  Arid: {c.arido_chr}")
    L.append(f"** Month/Season assignments: {'User-specified' if c.asigna_meses else 'Default'}")
    for lbl, txt in zip(LBL, [c.txt_inv_sin, c.txt_inv_con, c.txt_prim, c.txt_ver,
                              c.txt_oto]):
        L.append(f"** {lbl}: {txt}")
    L.append("")
    L.append("")
    sufijo = "2" if c.estacion == "SECONDARY" else ""
    L.append(f"   FREQ_SECT{sufijo or ' '} {c.res_temporal_txt}{fmt_i(c.num_sectores, 3)}"
             if sufijo else f"   FREQ_SECT  {c.res_temporal_txt}{fmt_i(c.num_sectores, 3)}")
    n = c.num_sectores
    sd = c.start_dir
    for i in range(n):
        if i == n - 1 and abs(sd[0] - 0.0) >= 1e-5:
            fin = sd[0]
        elif i == n - 1:
            fin = 360.0
        else:
            fin = sd[i + 1]
        kw = "SECTOR2" if sufijo else "SECTOR "
        L.append(f"   {kw}{fmt_i(i + 1, 3)}{fmt_f(sd[i], 8, 2)}{fmt_f(fin, 8, 2)}")
    L.append("")
    cab = {"M": "**           Month    Sect    Alb",
           "S": "**           Season   Sect    Alb"}.get(c.res_temporal,
                                                     "**                    Sect    Alb")
    L.append(cab + "      Bo        Zo")
    nf = {"A": 1, "S": 4, "M": 12}[c.res_temporal]
    kw = "SITE_CHAR2 " if sufijo else "SITE_CHAR  "
    for j in range(nf):
        for i in range(n):
            L.append(f"   {kw}{fmt_i(j + 1, 3)}     {fmt_i(i + 1, 3)}"
                     f"{fmt_f(r.alb[j], 9, 2)}{fmt_f(r.bowen[j], 9, 2)}{fmt_f(r.zo[i, j], 10, 3)}")
    with open(path, "w", encoding="latin-1", newline="\n") as f:
        f.write("\n".join(L) + "\n")


def _a(texto, w):
    """Descriptor Aw de Fortran: ajusta a la derecha si sobra, recorta si falta."""
    return texto[:w] if len(texto) >= w else texto.rjust(w)


def escribir_log(path, c, r, ahora=None):
    """Parte CALCULADA del .log del original (desde «Getting grid information»): rejillas,
    giro de Albers, cuentas por clase y sector, avisos y tablas de rugosidad y alcance. Las
    líneas previas del original (etiquetas internas del TIFF) se sustituyen por un resumen."""
    from . import tablas as T
    L = _cabecera(f"AERSURFACE Log File, Version {VERSION}", ahora)
    L += ["", " (Traducción Python: el volcado de etiquetas TIFF del original no se replica)"]
    nom = {"LC": ("NLCD", getattr(c, "_lc_nombre", "")),
           "Imp": ("MPRV", getattr(c, "_imp_nombre", "")),
           "Can": ("CNPY", getattr(c, "_can_nombre", ""))}
    for tipo in ("LC", "Imp", "Can"):
        if tipo not in r.rejillas:
            continue
        g = r.rejillas[tipo]
        dt_, fn = nom[tipo]
        L += ["", " ***************************", "",
              f" Getting grid information for {dt_}: {fn}",
              " Based on the following input coordinates, converted if needed to LATLON/NAD83: ",
              f"    Latitude:  {fmt_f(g.lat, 12, 6)}", f"    Longitude: {fmt_f(g.lon, 12, 6)}",
              "", " The study center is located at",
              f"    Albers projection X-coordinate: {fmt_f(g.cx, 10, 0)}",
              f"    Albers projection Y-coordinate: {fmt_f(g.cy, 10, 0)}",
              f"    Row in data file:   {fmt_i(g.fila_c, 8)}",
              f"    Column in data file:{fmt_i(g.col_c, 8)}",
              "", f" Rotation of Albers grid to true North (deg): {fmt_f(g.giro, 10, 5)}"]
    n = c.num_sectores
    L += ["", "***************************", "",
          f" Land Cover Counts: Surface Roughness (Within {fmt_i(int(r.zo_rad_final), 4)}m Radius)",
          "", " " * 29 + "SECTOR: " + "".join("    " + fmt_i(i + 1, 4) for i in range(n)),
          "Cat" + " " * 14 + "Starting Direction: " + "".join(
              "  " + fmt_f(c.start_dir[i], 6, 1) for i in range(n)), "-" * 36]
    for k in range(100):
        if k in T.NOMBRES or k == 0:
            nombre = T.NOMBRES.get(k, "")
            if nombre:
                L.append(" " + fmt_i(k, 2) + " " + _a(nombre, 31) + ": "
                         + "".join(fmt_i(r.cuentas_z0[i, k], 8) for i in range(n)))
    L += ["-" * 36, " " + _a("Total", 34) + ": " + "".join(
        fmt_i(int(r.cuentas_z0[i].sum()), 8) for i in range(n))]
    L += ["", " Land Cover Counts: Bowen Ratio and Albedo (10km X 10km Domain)", ""]
    for k in range(100):
        nombre = T.NOMBRES.get(k, "")
        if nombre:
            L.append(fmt_i(k, 3) + " " + _a(nombre, 31) + ": " + fmt_i(r.cuentas_br[k], 8))
    tot_br = int(r.cuentas_br.sum())
    L += ["-" * 36, " " + _a("Total", 34) + ": " + fmt_i(tot_br, 8), ""]
    # avisos de celdas ausentes (cocientes en precisión simple, como REAL()/REAL())
    f32 = np.float32
    if tot_br > 0:
        fr = f32(r.cuentas_br[0]) / f32(tot_br)
        if 0.001 <= fr <= 0.5:
            L += ["", f" WARNING: The land cover values for {fmt_f(float(fr * f32(100.)), 5, 1)}% of",
                  " the cells extracted to compute Bowen ratio and albedo",
                  " are either missing, outside of the NLCD file boundary,", " or invalid."]
    for i in range(n):
        tz = int(r.cuentas_z0[i].sum())
        if tz > 0:
            mz = int(r.cuentas_z0[i, 0])
            if 0.001 <= mz / tz <= 0.5:
                L += ["", f" WARNING: The land cover values for "
                      f"{fmt_f(float(f32(mz) / f32(tz) * f32(100.)), 5, 1)}% of",
                      " the cells extracted to compute surface roughness",
                      f" in sector {fmt_i(i + 1, 2)} are either missing, outside of the",
                      " NLCD file boundary, or invalid."]
    if r.canimp is not None and r.canimp[0] > 0 and r.canimp[1] / r.canimp[0] > 0.01:
        L += ["", " WARNING: The sum of the canopy + impervious percent",
              f" values for {fmt_f(r.canimp[1] / r.canimp[0] * 100.0, 5, 1)}% of the cells "
              "within a 1km", f" radius of the met tower exceeds {fmt_f(150.0, 5, 1)}%."]
    if r.ibl_txt:
        que, raw, lim = r.ibl_txt
        L += [f"WARNING: The calculated IBL height ({fmt_f(raw, 10, 1).strip()} m),",
              f"computed as the Anemometer Height X {fmt_f(c.ibl_factor, 4, 1)}, is",
              f"{que} allowed height ({fmt_f(lim, 10, 1).strip()} m).",
              f"The IBL height was reset to {fmt_f(lim, 10, 1).strip()} m."]
    L.append(f"** High Z0 (Non-Airport) Sector IDs: {_ids_no_aeropuerto(c)}")
    raya = "-" * 120
    cab = ["       Start" + " " * 49 + "Month",
           ("Sector  Dir " + "".join(fmt_i(m, 7) + "  " for m in range(1, 13))).rstrip()]
    L += ["", " Roughness (m) by Month and Sector", raya] + cab
    for i in range(n):
        L.append("  " + fmt_i(i + 1, 2) + "   " + fmt_f(c.start_dir[i], 5, 1)
                 + "".join(fmt_f(r.zo_mes[i, j], 9, 3) for j in range(12)))
    L += [raya, "", "", " Roughness Fetch (m) by Month and Sector", raya] + cab
    for i in range(n):
        L.append("  " + fmt_i(i + 1, 2) + "   " + fmt_f(c.start_dir[i], 5, 1)
                 + "".join(fmt_f(r.zo_fetch[i, j], 9, 1) for j in range(12)))
    L += [raya, " ", " Average Roughness Fetch (m) =  " + fmt_f(r.fetch_medio, 7, 1)]
    with open(path, "w", encoding="latin-1", newline="\n") as f:
        f.write("\n".join(L) + "\n")


def escribir_rejilla(path, g, tipo, nombre_tiff, inicial, ahora=None):
    v = g.vars
    t = {"LC": "Land Cover", "Imp": "Impervious", "Can": "Canopy"}[tipo].ljust(10)  # LEN=10
    L = _cabecera(f"AERSURFACE Grid Debug File, Version {VERSION}", ahora)
    L.append(f"10km x 10km {t} Data Grid Extracted from: {nombre_tiff}")
    L.append(f"Centered On: {fmt_f(g.lat, 12, 6)}, {fmt_f(g.lon, 12, 6)} (NAD83)")
    L.append("")
    nf, nc = g.datos.shape
    L.append("ncols".ljust(31) + fmt_i(nc, 10))
    L.append("nrows".ljust(31) + fmt_i(nf, 10))
    L.append("xllcorner".ljust(32) + fmt_f(g.ll_x, 11, 1))
    L.append("yllcorner".ljust(32) + fmt_f(g.ll_y, 11, 1))
    L.append("cellsize".ljust(33) + fmt_f(v.cell_res, 12, 3))
    L.append("NODATA_value".ljust(40) + "0")
    for j in range(nf):
        fila = g.fila0 + j
        if 1 <= fila <= v.rows:
            y = nint(float(v.ul_y) - (fila - 1) * v.cell_res)
        else:
            y = inicial
        vals = g.datos[j].tolist()
        L.append(fmt_i(y, 15) + ". : " + " ".join(
            _I3[x] if -999 <= x <= 999 else fmt_i(x, 3) for x in vals))
    with open(path, "w", encoding="latin-1", newline="\n") as f:
        f.write("\n".join(L) + "\n")
